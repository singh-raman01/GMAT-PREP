// Builds the release: the web app, then one executable per target OS with the
// web app, migrations and Taxonomy embedded.
//
//   bun run build         this computer's OS and CPU
//   bun run build:all     every supported target
import { $ } from "bun"
import { mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs"
import { join, relative, sep } from "node:path"

const Targets = [
  "bun-linux-x64",
  "bun-linux-arm64",
  "bun-darwin-x64",
  "bun-darwin-arm64",
  "bun-windows-x64"
] as const

const root = join(import.meta.dir, "..")
const webDist = join(root, "web", "dist")
const buildDir = join(root, ".build")
const outDir = join(root, "dist")

const hostTarget = `bun-${process.platform === "win32" ? "windows" : process.platform}-${process.arch}`
const targets = process.argv.includes("--all") ? [...Targets] : [hostTarget]

const filesUnder = (dir: string): ReadonlyArray<string> =>
  readdirSync(dir).flatMap((name) => {
    const path = join(dir, name)
    return statSync(path).isDirectory() ? filesUnder(path) : [path]
  })

console.log("Building the web app")
// --bun runs Vite on Bun rather than on whatever Node is installed.
await $`bun x --bun vite build --config web/vite.config.ts --logLevel warn`.cwd(root)
await $`bun scripts/gen-migrations-index.ts`.cwd(root)

// An entry that imports every web file as an embedded file, registers them by
// URL path, then starts the app.
const assets = filesUnder(webDist).toSorted()
const toPosix = (path: string) => path.split(sep).join("/")
const entry = [
  "// Generated by scripts/build.ts. Do not edit.",
  `import { registerEmbeddedAssets } from "../src/server/http/web.ts"`,
  `import { main } from "../src/server/main.ts"`,
  ...assets.map((file, i) => `import f${i} from ${JSON.stringify(toPosix(relative(buildDir, file)))} with { type: "file" }`),
  "",
  "registerEmbeddedAssets({",
  ...assets.map((file, i) => `  ${JSON.stringify(`/${toPosix(relative(webDist, file))}`)}: f${i},`),
  "})",
  "main()",
  ""
].join("\n")
rmSync(buildDir, { recursive: true, force: true })
mkdirSync(buildDir, { recursive: true })
writeFileSync(join(buildDir, "entry.ts"), entry)
mkdirSync(outDir, { recursive: true })

for (const target of targets) {
  const name = `gmat-prep-${target.replace(/^bun-/, "")}${target.includes("windows") ? ".exe" : ""}`
  const outfile = join(outDir, name)
  console.log(`Compiling ${name}`)
  await $`bun build ${join(buildDir, "entry.ts")} --compile --target=${target} --minify-syntax --minify-whitespace --outfile ${outfile}`
    .cwd(root)
}
console.log(`Done. Executables are in ${relative(root, outDir) || "."}${sep}`)
